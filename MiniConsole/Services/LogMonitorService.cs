using System.Text;
using MiniConsole.Views;
using MiniConsole.Configuration;

namespace MiniConsole.Services
{
    public class LogMonitorService
    {
        private readonly AppSettings _settings;
        private readonly JsonStreamManager _streamManager;

        public LogMonitorService(AppSettings settings, JsonStreamManager streamManager)
        {
            _settings = settings;
            _streamManager = streamManager;
        }

        public void StartMonitoring(string logFilePath)
        {
            using var fs = new FileStream(
                logFilePath,
                FileMode.Open,
                FileAccess.ReadWrite,
                FileShare.ReadWrite,
                _settings.ReadBufferSize);

            long lastReadPosition = fs.Length;
            string incompleteLineBuffer = string.Empty;
            byte[] readBuffer = new byte[_settings.ReadBufferSize];

            while (true)
            {
                long currentFileLength = fs.Length;

                if (currentFileLength < lastReadPosition)
                {
                    lastReadPosition = 0;
                    incompleteLineBuffer = string.Empty;
                }

                if (currentFileLength > lastReadPosition)
                {
                    fs.Seek(lastReadPosition, SeekOrigin.Begin);
                    int bytesToRead = (int)Math.Min(readBuffer.Length, currentFileLength - lastReadPosition);
                    int bytesRead = fs.Read(readBuffer, 0, bytesToRead);

                    if (bytesRead > 0)
                    {
                        lastReadPosition += bytesRead;

                        // Strip null bytes ('\0') generated by OS pointer offset after file truncation
                        string chunk = Encoding.UTF8.GetString(readBuffer, 0, bytesRead).Replace("\0", string.Empty);
                        string combined = incompleteLineBuffer + chunk;

                        int lineStart = 0;
                        int newlineIdx;

                        // Process only complete lines ending with '\n'
                        while ((newlineIdx = combined.IndexOf('\n', lineStart)) != -1)
                        {
                            string completeLine = combined.Substring(lineStart, newlineIdx - lineStart).TrimEnd('\r');
                            lineStart = newlineIdx + 1;

                            if (string.IsNullOrWhiteSpace(completeLine))
                            {
                                continue;
                            }

                            int cmdIdx = completeLine.IndexOf("@@", StringComparison.Ordinal);
                            if (cmdIdx != -1)
                            {
                                string cmdPayload = completeLine.Substring(cmdIdx);
                                if (ProcessEngineCommand(cmdPayload, fs, ref lastReadPosition, ref incompleteLineBuffer))
                                {
                                    break; // Log was cleared, exit current chunk processing loop
                                }
                            }
                            else
                            {
                                string displayLine = _settings.RemoveLogTags ? StripLogTagFast(completeLine) : completeLine;
                                ConsoleRenderer.PrintStandardLog(completeLine, displayLine);
                            }
                        }

                        // Retain remaining partial line for the next polling cycle
                        if (lastReadPosition != 0 && lineStart < combined.Length)
                        {
                            incompleteLineBuffer = combined.Substring(lineStart);
                        }
                        else
                        {
                            incompleteLineBuffer = string.Empty;
                        }
                    }
                }

                Thread.Sleep(_settings.PollIntervalMs);
            }
        }

        private bool ProcessEngineCommand(string cmdLine, FileStream fs, ref long lastPos, ref string incompleteBuffer)
        {
            // 1. Batch JSON Write: @@JSON_BATCH|FileKey|{json1}~~{json2}
            if (cmdLine.StartsWith("@@JSON_BATCH|", StringComparison.Ordinal))
            {
                int secondPipe = cmdLine.IndexOf('|', 13);
                if (secondPipe != -1)
                {
                    string fileKey = cmdLine.Substring(13, secondPipe - 13).Trim();
                    string payload = cmdLine.Substring(secondPipe + 1).Trim();
                    _streamManager.WriteBatch(fileKey, payload);
                }
                return false;
            }

            // 2. Progress Update: @@PROG|Current|Total|LuaFoundCount(|FORCE)
            if (cmdLine.StartsWith("@@PROG|", StringComparison.Ordinal))
            {
                bool forceRender = cmdLine.EndsWith("|FORCE", StringComparison.Ordinal);
                string[] parts = cmdLine.Split('|');
                if (parts.Length >= 4 &&
                    long.TryParse(parts[1], out long current) &&
                    long.TryParse(parts[2], out long total))
                {
                    long written = _streamManager.TotalWrittenAcrossStreams;
                    string status = $"Lua Found: {parts[3]} | Written: {written:N0}";
                    ConsoleRenderer.RenderProgressBar(current, total, status, forceRender);
                }
                return false;
            }

            // 3. Clear Log Buffer: @@CLEAR_LOG
            if (cmdLine.StartsWith("@@CLEAR_LOG", StringComparison.Ordinal))
            {
                fs.SetLength(0);
                fs.Seek(0, SeekOrigin.Begin);
                lastPos = 0;
                incompleteBuffer = string.Empty;

                _streamManager.FlushAll();
                return true;
            }

            // 4. Open JSON Stream: @@OPEN_JSON|FileKey|FullPath
            if (cmdLine.StartsWith("@@OPEN_JSON|", StringComparison.Ordinal))
            {
                string[] parts = cmdLine.Split('|');
                if (parts.Length >= 3)
                {
                    _streamManager.OpenStream(parts[1].Trim(), parts[2].Trim());
                }
                return false;
            }

            // 5. Close JSON Stream: @@CLOSE_JSON|FileKey
            if (cmdLine.StartsWith("@@CLOSE_JSON|", StringComparison.Ordinal))
            {
                string fileKey = cmdLine.Substring(13).Trim();
                _streamManager.CloseStream(fileKey);
                return false;
            }

            return false;
        }

        private static string StripLogTagFast(string line)
        {
            // Fast index-based tag stripping for "[HH:mm:ss][channel] message"
            if (line.Length >= 18 && line[0] == '[' && line[9] == ']' && line[10] == '[')
            {
                int endIdx = line.IndexOf(']', 11);
                if (endIdx != -1)
                {
                    int start = endIdx + 1;
                    if (start < line.Length && line[start] == ' ')
                    {
                        start++;
                    }
                    return line.Substring(start);
                }
            }
            return line;
        }
    }
}
